"""EWMA workload profile: an online estimate of the recent job-class mix.

Used by the workload-aware policies in sim/experimental.py. The profile is
the ONLY stateful object in the policy stack, and it is deliberately
simple and fully deterministic:

Distribution update (exponentially weighted moving average, decay eta):

    p_{t+1}(b) = (1 - eta) * p_t(b) + eta * 1[b == b_t]

where `b_t` is the bucket of the job observed at step t. `p` always sums
to 1 (up to float error) because the update is a convex combination of
two distributions.

Prediction-error tracking (measured BEFORE the update, so the profile is
always judged on what it predicted, never on what it just learned):

    err_{t+1} = (1 - eta) * err_t + eta * (1 - p_t(b_t))

`1 - p_t(b_t)` is the probability mass the profile did NOT assign to the
bucket that actually arrived; 0 = perfect prediction, ~1 = the arriving
bucket was considered near-impossible.

Confidence (used to shrink the future-fit weight gamma):

    chance     = 1 - 1/B          (error of the uniform distribution)
    confidence = clamp(1 - err / chance, 0, 1)

confidence == 1 -> profile predicts perfectly; confidence == 0 -> profile
is at (or worse than) chance level, so a workload-aware term relying on
it should be ignored. Both `err` and `p` start at the uniform prior, so
confidence starts at 0 and must be EARNED from observations -- an
unwarmed profile never boosts the workload-aware term.

Buckets: the canonical 9 (size_class x shape) classes from sim.workload.
This is generator-aligned: the workload generator emits exactly these
classes, so a quantile-based discretization would re-derive the same
boundaries with extra machinery. `bucket_of` still handles jobs with
non-canonical labels by snapping to the nearest canonical class
(nearest total size, nearest CPU share), so the profile is usable with
ad hoc jobs too. The bucket set is a constructor argument, not a
hard-coded global, so alternative discretizations remain possible.
"""

from __future__ import annotations

from typing import Dict, Sequence, Tuple

from sim.models import Job
from sim.workload import SHAPES, SIZES, class_key, job_resources

# Canonical bucket keys, e.g. "small_balanced" ... "large_ram_heavy".
CANONICAL_BUCKETS: Tuple[str, ...] = tuple(
    class_key(size, shape) for size in SIZES for shape in SHAPES
)

# Representative (cpu, ram) demand for each canonical bucket.
BUCKET_RESOURCES: Dict[str, Tuple[float, float]] = {
    class_key(size, shape): job_resources(size, shape)
    for size in SIZES
    for shape in SHAPES
}


def bucket_of(job: Job) -> str:
    """Map a job to a canonical bucket key.

    Jobs generated by sim.workload carry canonical (size_class, shape)
    labels and map exactly. Jobs with other labels are snapped to the
    nearest canonical class: nearest size by |total demand - class total|,
    nearest shape by |cpu share - shape cpu share|. Deterministic; ties
    resolve to the lexically-first name via sorted iteration.
    """
    if job.size_class in SIZES and job.shape in SHAPES:
        return class_key(job.size_class, job.shape)
    total = job.cpu + job.ram
    # Job model guarantees total > 0.
    cpu_share = job.cpu / total
    size = min(sorted(SIZES), key=lambda s: abs(SIZES[s] - total))
    shape = min(sorted(SHAPES), key=lambda sh: abs(SHAPES[sh].cpu_share - cpu_share))
    return class_key(size, shape)


class WorkloadProfile:
    """Mutable EWMA estimate of the recent job-class distribution.

    See module docstring for the exact update and confidence formulas.
    """

    __slots__ = ("decay", "p", "err", "observed", "_chance", "_buckets")

    def __init__(
        self,
        decay: float = 0.1,
        buckets: Sequence[str] = CANONICAL_BUCKETS,
    ) -> None:
        if not (0.0 < decay <= 1.0):
            raise ValueError(f"decay must be in (0, 1], got {decay!r}")
        buckets = tuple(buckets)
        if len(buckets) < 2:
            raise ValueError("profile needs at least 2 buckets")
        if len(set(buckets)) != len(buckets):
            raise ValueError("bucket names must be unique")
        for b in buckets:
            if b not in BUCKET_RESOURCES:
                raise ValueError(f"unknown bucket {b!r}; valid: {sorted(BUCKET_RESOURCES)}")
        self.decay = decay
        self._buckets = buckets
        uniform = 1.0 / len(buckets)
        self.p: Dict[str, float] = {b: uniform for b in buckets}
        self._chance = 1.0 - uniform
        self.err = self._chance  # start at chance level -> confidence 0
        self.observed = 0

    @property
    def buckets(self) -> Tuple[str, ...]:
        return self._buckets

    def observe(self, job: Job) -> None:
        """Fold one observed job into the profile (predict-then-update)."""
        b = bucket_of(job)
        if b not in self.p:
            raise KeyError(f"bucket {b!r} not tracked by this profile")
        # Error is measured against the PRE-update prediction.
        self.err = (1.0 - self.decay) * self.err + self.decay * (1.0 - self.p[b])
        for k in self.p:
            self.p[k] *= 1.0 - self.decay
        self.p[b] += self.decay
        self.observed += 1

    @property
    def confidence(self) -> float:
        """1 = perfect recent predictions, 0 = at/below chance level."""
        return max(0.0, min(1.0, 1.0 - self.err / self._chance))

    def demand_shares(self) -> Tuple[float, float]:
        """Profile-implied mean (cpu_share, ram_share) of arriving jobs.

        cpu_share_b = cpu_b / (cpu_b + ram_b) for each bucket's
        representative job; the profile mean is sum_b p(b) * cpu_share_b.
        Uses the job's own demand ratio (unit caveat: CPU and RAM units
        are not physically commensurable; this is a documented modeling
        simplification, mitigated by capacity-normalized comparison on
        the node side -- see sim/experimental.py).
        """
        cpu_share = 0.0
        for b, prob in self.p.items():
            cpu, ram = BUCKET_RESOURCES[b]
            cpu_share += prob * (cpu / (cpu + ram))
        return cpu_share, 1.0 - cpu_share
