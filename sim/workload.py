"""Seeded workload and cluster generation for the placement simulation.

METHODOLOGY CORRECTION (see METHODOLOGY_CORRECTION_REPORT.md): the previous
version of this module generated jobs from five labels --
`small, medium, large, cpu-heavy, ram-heavy` -- treated as one axis. That
was methodologically wrong: `small/medium/large` describe total resource
*magnitude*, while `cpu-heavy/ram-heavy` describe CPU:RAM *ratio*. Treating
them as five points on a single axis made it impossible to ask "is a small
CPU-heavy job placed differently than a small balanced job of the same
total size?" -- the two dimensions were entangled.

This module generates every job from an explicit, independent
`(size_class, shape)` pair:

- `shape` (`SHAPES`) fixes the CPU:RAM *ratio* only -- it says nothing
  about magnitude.
- `size_class` (`SIZES`) fixes the total resource *magnitude* (`cpu + ram`)
  only -- it says nothing about ratio.

A job's CPU/RAM demand is `cpu = size * shape.cpu_share`,
`ram = size * shape.ram_share`. Two jobs of the same size but different
shape have equal `cpu + ram` and different ratios; two jobs of the same
shape but different size have equal ratios and different magnitudes.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from typing import Dict, List, Mapping, Tuple

from sim.models import Job, NodeState

# --- Resource shape: CPU:RAM ratio, independent of magnitude -------------


@dataclass(frozen=True)
class ResourceShape:
    name: str
    cpu_share: float
    ram_share: float

    def __post_init__(self) -> None:
        total = self.cpu_share + self.ram_share
        if abs(total - 1.0) > 1e-9:
            raise ValueError(
                f"shape {self.name!r}: cpu_share + ram_share must equal 1.0, got {total!r}"
            )
        if self.cpu_share <= 0 or self.ram_share <= 0:
            raise ValueError(f"shape {self.name!r}: shares must be > 0")


SHAPES: Dict[str, ResourceShape] = {
    "balanced": ResourceShape("balanced", cpu_share=0.50, ram_share=0.50),
    "cpu_heavy": ResourceShape("cpu_heavy", cpu_share=0.80, ram_share=0.20),
    "ram_heavy": ResourceShape("ram_heavy", cpu_share=0.20, ram_share=0.80),
}

# --- Size class: total resource magnitude, independent of shape ----------

# Fixed, documented total (cpu + ram) demand per size class. Values are
# arbitrary but fixed: they only need to (a) stay well under the smallest
# node's capacity generated by `generate_cluster`'s default ranges, and
# (b) stay ordered small < medium < large so the classes are meaningfully
# distinct.
SIZES: Dict[str, float] = {
    "small": 10.0,
    "medium": 25.0,
    "large": 40.0,
}

CANONICAL_CLASSES: Tuple[Tuple[str, str], ...] = tuple(
    (size, shape) for size in SIZES for shape in SHAPES
)


def class_key(size_class: str, shape: str) -> str:
    """Canonical string key for a (size_class, shape) pair, e.g. 'small_cpu_heavy'."""
    return f"{size_class}_{shape}"


def job_resources(size_class: str, shape: str) -> Tuple[float, float]:
    """Return (cpu, ram) demand for a canonical (size_class, shape) pair.

    Raises ValueError for unknown size_class or shape names.
    """
    if size_class not in SIZES:
        raise ValueError(f"unknown size_class {size_class!r}; valid: {sorted(SIZES)}")
    if shape not in SHAPES:
        raise ValueError(f"unknown shape {shape!r}; valid: {sorted(SHAPES)}")
    total = SIZES[size_class]
    s = SHAPES[shape]
    return total * s.cpu_share, total * s.ram_share


def generate_workload(
    size_shape_counts: Mapping[Tuple[str, str], int],
    seed: int,
    shuffle: bool = True,
) -> Tuple[Job, ...]:
    """Generate an exact, deterministic workload from (size_class, shape) counts.

    `size_shape_counts` maps `(size_class, shape) -> count`, e.g.
    `{("small", "balanced"): 10, ("medium", "cpu_heavy"): 5}`.

    Properties:
    - Every job of a given (size_class, shape) has *identical* CPU/RAM
      demand -- size and shape are the controlled variables in this
      simulation, so no per-job noise is added within a class. (Contrast
      with the previous per-shape `rng.uniform(*range)` design, which let
      random draws blur the size/shape boundary it was supposed to test.)
    - Job IDs are deterministic and unique: `job-<size>-<shape>-<index>`,
      assigned before shuffling.
    - `shuffle=True` randomizes arrival order using a *local*
      `random.Random(seed)` instance -- this never reads or mutates the
      global `random` module's state, so it cannot affect (or be affected
      by) unrelated code that also uses `random`.
    - Same `(size_shape_counts, seed, shuffle)` always produces the exact
      same job tuple, in the exact same order.
    - Unknown size_class/shape names or negative counts raise ValueError
      before any jobs are generated (fail fast, no partial workload).
    """
    for (size_class, shape), count in size_shape_counts.items():
        if size_class not in SIZES:
            raise ValueError(f"unknown size_class {size_class!r}; valid: {sorted(SIZES)}")
        if shape not in SHAPES:
            raise ValueError(f"unknown shape {shape!r}; valid: {sorted(SHAPES)}")
        if count < 0:
            raise ValueError(
                f"count for ({size_class!r}, {shape!r}) must be >= 0, got {count!r}"
            )

    jobs: List[Job] = []
    # Sort keys for a deterministic generation order independent of the
    # caller's mapping/dict iteration order (dicts preserve insertion order
    # in Python, but sorting removes any dependency on how the caller built
    # the mapping).
    for size_class, shape in sorted(size_shape_counts.keys()):
        count = size_shape_counts[(size_class, shape)]
        cpu, ram = job_resources(size_class, shape)
        for i in range(count):
            job_id = f"job-{size_class}-{shape}-{i:04d}"
            jobs.append(
                Job(job_id=job_id, cpu=cpu, ram=ram, shape=shape, size_class=size_class)
            )

    if shuffle:
        rng = random.Random(seed)
        rng.shuffle(jobs)  # shuffles the local `jobs` list in place; global `random` untouched

    return tuple(jobs)


def generate_cluster(
    n_nodes: int,
    seed: int,
    cpu_range: Tuple[float, float] = (64.0, 128.0),
    ram_range: Tuple[float, float] = (64.0, 256.0),
) -> Tuple[NodeState, ...]:
    """Generate `n_nodes` empty nodes with randomized (but deterministic)
    heterogeneous capacity.

    Node IDs (`node-000`, `node-001`, ...) are assigned in generation
    order and are used only as human-readable labels -- see
    sim/scheduler.py for why placement tie-breaking does not use node_id.
    """
    if n_nodes <= 0:
        raise ValueError(f"n_nodes must be > 0, got {n_nodes!r}")
    rng = random.Random(seed)
    nodes = []
    for i in range(n_nodes):
        total_cpu = rng.uniform(*cpu_range)
        total_ram = rng.uniform(*ram_range)
        nodes.append(NodeState(f"node-{i:03d}", total_cpu=total_cpu, total_ram=total_ram))
    return tuple(nodes)
